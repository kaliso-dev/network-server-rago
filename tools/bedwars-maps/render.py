def colour(b, d):
    if b in (35, 171, 95, 160):
        return DYE[d & 15]
    if b == 159:
        return CLAY[d & 15]
    if b in (5, 125, 126):
        return WOOD[d & 7 if d & 7 < 6 else 0]
    return BASE.get(b, (150, 150, 150))


def render(w, marks=(), scale=4, ymax=255, path='out.png', title=None):
    """marks: (x, z, colour, label)."""
    ids = w.ids[:, :ymax + 1, :]
    present = ids != 0
    top = np.where(present.any(axis=1), ids.shape[1] - 1 - np.argmax(present[:, ::-1, :], axis=1), -1)
    lo, hi = w.lo, w.hi
    x1, x2, z1, z2 = lo[0], hi[0], lo[2], hi[2]
    W, D = x2 - x1 + 1, z2 - z1 + 1
    img = np.zeros((D, W, 3), dtype=np.uint8)
    img[:] = (24, 24, 32)
    ys = top[x1:x2 + 1, z1:z2 + 1]
    valid = ys >= 0
    ymin = ys[valid].min() if valid.any() else 0
    yrange = max(1, (ys[valid].max() if valid.any() else 1) - ymin)
    for i in range(W):
        for k in range(D):
            y = ys[i, k]
            if y < 0:
                continue
            b = int(w.ids[x1 + i, y, z1 + k])
            d = int(w.data[x1 + i, y, z1 + k])
            c = np.array(colour(b, d), dtype=float)
            shade = 0.6 + 0.4 * (y - ymin) / yrange
            img[k, i] = np.clip(c * shade, 0, 255)
    im = Image.fromarray(img).resize((W * scale, D * scale), Image.NEAREST)
    dr = ImageDraw.Draw(im)
    for (x, z, col, label) in marks:
        px = (x - (x1 + w.x0)) * scale
        pz = (z - (z1 + w.z0)) * scale
        r = scale * 1.2
        dr.ellipse([px - r, pz - r, px + r, pz + r], outline=(0, 0, 0), fill=col)
        if label:
            dr.text((px + r + 1, pz - r - 1), label, fill=(255, 255, 255), stroke_width=2, stroke_fill=(0, 0, 0))
    # world coordinates grid every 16 blocks
    for gx in range((x1 + w.x0) // 16 * 16, x2 + w.x0 + 1, 16):
        px = (gx - (x1 + w.x0)) * scale
        dr.line([px, 0, px, 6], fill=(255, 255, 255))
        dr.text((px + 2, 0), str(gx), fill=(200, 200, 200))
    for gz in range((z1 + w.z0) // 16 * 16, z2 + w.z0 + 1, 16):
        pz = (gz - (z1 + w.z0)) * scale
        dr.line([0, pz, 6, pz], fill=(255, 255, 255))
        dr.text((8, pz + 1), str(gz), fill=(200, 200, 200))
    if title:
        dr.text((4, im.size[1] - 14), title, fill=(255, 255, 255), stroke_width=2, stroke_fill=(0, 0, 0))
    im.save(path)
    return path
